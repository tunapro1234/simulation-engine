"""ABM workflow: adoption-curve ABM calibrated with ABC (+ analogy prior from other series), backtested against
curve baselines and the Bass-simulator control, scored with the evidence pipeline. Offline, synthetic series.

    python examples/abm_adoption.py

Small banks (300 sims x 300 agents) keep this under a minute; the measured defaults are 2,000 x 2,000 and smaller
banks were not measured. Measured guidance (docs/RESULTS.md, makro M1): on OWID internet test series the analogy
ABM had MAE 8.48 pp vs 9.73 for the Bass-simulator control and 10.72 for a linear trend; most of the gain came from
ABC + the analogy prior, not the ABM structure; at h=1 simple baselines win, and on mixed US household technologies
the analogy prior hurt (10.07 vs 8.54).
"""
import numpy as np
import pandas as pd

import simengine as se
import simengine.abm as abm

# Synthetic Bass-shaped adoption series (percent), staggered starts: one kind of technology across 8 "countries".
# The data are generated by a Bass curve, so the Bass-simulator control is expected to do well here.
rng = np.random.default_rng(0)
rows = []
for i in range(8):
    t = np.arange(1990, 2021, dtype=float)
    y = abm.bass_curve(t, 60 + 5 * i, 0.01 * (1 + i % 3), 0.3 + 0.05 * i, 1990 + i) + rng.normal(0, 0.5, len(t))
    rows += [{"series": f"c{i}", "t": tt, "y": float(np.clip(yy, 0, 100))} for tt, yy in zip(t, y)]
df = pd.DataFrame(rows)

small = dict(n_sim=300, n_agents=300, seed=0)
methods = {"abm_analogy": abm.AdoptionABCAnalogy(**small), "bass_control": abm.BassABCAnalogy(**small),
           "linear": abm.CurveBaseline("linear"), "gompertz": abm.CurveBaseline("gompertz"),
           "naive": abm.CurveBaseline("naive")}
frame = abm.adoption_backtest(df, methods, cutoffs=(3, 5), horizon=10)     # each method sees only t <= cutoff
frame = frame.drop(columns=[c for c in frame.columns if c.startswith(("lo80_", "hi80_"))])
print(frame.groupby("horizon").size().head(3).to_dict(), "rows:", len(frame))
for m in methods:
    print(f"MAE {m:13s} {np.abs(frame[f'pred_{m}'] - frame.truth).mean():6.2f} pp")

report = se.evidence.evaluate(frame, title="adoption backtest (synthetic)", ours="abm_analogy", raw="bass_control",
                              task="continuous", primary="mae", unlabeled_baselines=["naive", "linear", "gompertz"],
                              multiplier=False, B=300)
print(se.evidence.summary(report)["headline"])

# Model-implied counterfactual and adopter shares (label them as model output, not observations).
fit = methods["abm_analogy"].fit(df[df.t <= 2000], "c3", 2000.0)
print(methods["abm_analogy"].scenario(fit, {"imitation": 1.2}, n_draws=20).groupby("scenario").y_pred.mean())
